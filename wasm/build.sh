#!/bin/sh
# Compiles precise.c to WebAssembly and packs it into js/precise-wasm.js (as
# base64 text, so the page needs no extra file and also works from a plain
# folder). Needs clang with the wasm32 target (e.g. clang 15 or later).
set -e
cd "$(dirname "$0")"
clang --target=wasm32 -O3 -nostdlib -ffp-contract=off -fno-fast-math \
  -Wl,--no-entry -Wl,--export-memory -o precise.wasm precise.c
{
  echo "// Generated by wasm/build.sh from wasm/precise.c. Do not edit."
  echo "export const PRECISE_WASM = '$(base64 -w0 precise.wasm)';"
} > ../js/precise-wasm.js
rm precise.wasm
echo "js/precise-wasm.js: $(wc -c < ../js/precise-wasm.js) bytes"
